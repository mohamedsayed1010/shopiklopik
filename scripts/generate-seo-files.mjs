
import { writeFileSync, readFileSync, existsSync, mkdirSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));

const root = resolve(here, "..");

const publicDir = join(root, "public");

/** `VITE_SITE_URL` from the environment, or from a local .env file. */
function siteUrl() {
  if (process.env.VITE_SITE_URL) return process.env.VITE_SITE_URL.trim();

  for (const name of [".env.production", ".env.local", ".env"]) {
    const file = join(root, name);

    if (!existsSync(file)) continue;

    const match = readFileSync(file, "utf8").match(
      /^\s*VITE_SITE_URL\s*=\s*(.+)$/m
    );

    if (match) return match[1].trim().replace(/^["']|["']$/g, "");
  }

  return "";
}

async function loadPolicy() {
  const module = await import(
    new URL("../src/seo/routePolicy.js", import.meta.url).href
  );

  return module;
}

function buildRobots({ privatePrefixes, noindexPaths, sitemap }) {
  const lines = [
    "# Generated by scripts/generate-seo-files.mjs — edit src/seo/routePolicy.js.",
    "",
    "User-agent: *",
    "",
    "# One person's own data, and the moderation console. Nothing here is",
    "# reachable without signing in, and none of it belongs in a search result.",
    // No trailing slash: a robots rule is a prefix match, so `/profile` covers
    // the page itself as well as everything under it. `/profile/` would not.
    ...privatePrefixes.map((prefix) => `Disallow: ${prefix}`),
    "",
    "# Reachable without an account, but a search result pointing at a sign-in",
    "# form helps nobody. These are also marked noindex in the page itself.",
    ...noindexPaths.map((path) => `Disallow: ${path}`),
    "",
    "# Everything else is allowed.",
    "Allow: /",
  ];

  if (sitemap) lines.push("", `Sitemap: ${sitemap}`);

  return `${lines.join("\n")}\n`;
}

function buildSitemap(origin, entries) {
  const today = new Date().toISOString().slice(0, 10);

  const urls = entries
    .map(({ path, changefreq, priority }) =>
      [
        "  <url>",
        `    <loc>${origin}${path}</loc>`,
        `    <lastmod>${today}</lastmod>`,
        `    <changefreq>${changefreq}</changefreq>`,
        `    <priority>${priority}</priority>`,
        "  </url>",
      ].join("\n")
    )
    .join("\n");

  return [
    '<?xml version="1.0" encoding="UTF-8"?>',
    '<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">',
    urls,
    "</urlset>",
    "",
  ].join("\n");
}

async function main() {
  const { PRIVATE_PREFIXES, NOINDEX_PATHS, SITEMAP_PATHS } = await loadPolicy();

  if (!existsSync(publicDir)) mkdirSync(publicDir, { recursive: true });

  const origin = siteUrl().replace(/\/+$/, "");

  const sitemapUrl = origin ? `${origin}/sitemap.xml` : "";

  writeFileSync(
    join(publicDir, "robots.txt"),
    buildRobots({
      privatePrefixes: PRIVATE_PREFIXES,
      noindexPaths: NOINDEX_PATHS,
      sitemap: sitemapUrl,
    }),
    "utf8"
  );

  console.log("[seo] wrote public/robots.txt");

  if (!origin) {
    console.log(
      "[seo] VITE_SITE_URL is not set — skipping sitemap.xml. " +
        "A sitemap needs absolute URLs, and this project records no domain."
    );

    return;
  }

  writeFileSync(
    join(publicDir, "sitemap.xml"),
    buildSitemap(origin, SITEMAP_PATHS),
    "utf8"
  );

  console.log(
    `[seo] wrote public/sitemap.xml with ${SITEMAP_PATHS.length} URL(s)`
  );
}

main().catch((error) => {
  // Never fail a build over metadata.
  console.warn("[seo] skipped:", error?.message ?? error);
});
